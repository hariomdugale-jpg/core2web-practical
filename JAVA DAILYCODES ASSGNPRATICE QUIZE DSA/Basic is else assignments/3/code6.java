

class IfElseDemo{

	public static void main(String[] args){

		int x = 15;
		if(x % 7 == 0 ){

			System.out.println("x is divisiable by the 7 ");
		}else if(x % 3 == 0){
			System.out.println("x is divisiable by the 3 ");

		}else{
			System.out.println("x is not divisiable by the 7 or 3");


		}

		

	}

}
