import java.util.Scanner;

class IfElse{

	public static void main(String[] args){

		Scanner s = new Scanner(System.in);
		System.out.println("enter your integer as input : ");
		int x = s.nextInt();

		if(x >= 1 && x <= 1000){

			System.out.println(x+"in the of 1 to 1000");
		}else{

			System.out.println(x+"in the of 1 to 1000");

		}

	}


}
